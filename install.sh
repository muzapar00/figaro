#!/usr/bin/env bash
# Install Figaro: overlay QML, systemd user units, and the config scaffold.
#
# Does not touch secrets: ~/.config/figaro/config.json must exist already
# (see config/config.example.json) and is never overwritten here.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
qs_cfg="${XDG_CONFIG_HOME:-$HOME/.config}/quickshell/figaro"
unit_dir="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
node="${FIGARO_NODE:-$(command -v node || echo /usr/bin/node)}"
node_bin_dir="$(dirname "$node")"
qs="${FIGARO_QS:-$(command -v qs || echo "$HOME/.local/bin/qs")}"

# The systemd units and the desktop entry are templates: they carry @REPO@,
# @NODE@, @QS@, @HOME@ and @NODE_BIN_DIR@ so a checkout can live anywhere and
# the units are generated at install time instead of pointing at one machine.
render() {
  local src="$1" dst="$2"
  # A previous install may have left a symlink here (older versions linked the
  # unit straight out of the checkout). Writing through it would recreate files
  # inside the repo and leave systemd with a dangling link, so drop it first.
  rm -f "$dst"
  sed -e "s|@REPO@|$repo|g" \
      -e "s|@NODE@|$node|g" \
      -e "s|@NODE_BIN_DIR@|$node_bin_dir|g" \
      -e "s|@QS@|$qs|g" \
      -e "s|@HOME@|$HOME|g" \
      "$src" > "$dst"
}

echo "== figaro: installing from $repo (node: $node, qs: $qs)"

if [[ ! -f "$HOME/.config/figaro/config.json" ]]; then
  echo "!! ~/.config/figaro/config.json is missing." >&2
  echo "   Create it from config/config.example.json and set the API keys." >&2
  exit 1
fi

if [[ ! -d "$repo/node_modules" ]]; then
  echo "== npm install"
  ( cd "$repo" && npm install --no-audit --no-fund )
fi

echo "== overlay -> $qs_cfg"
mkdir -p "$qs_cfg"
rsync -a --delete "$repo/qml/" "$qs_cfg/" --exclude test --exclude ctl.sh

if [[ -d "$repo/settings" ]]; then
  echo "== settings app -> $qs_cfg-settings"
  mkdir -p "${qs_cfg}-settings"
  rsync -a --delete "$repo/settings/" "${qs_cfg}-settings/" --exclude test --exclude '*.sh'
  if [[ -f "$repo/systemd/figaro-settings.desktop.in" ]]; then
    mkdir -p "$HOME/.local/share/applications"
    render "$repo/systemd/figaro-settings.desktop.in" "$HOME/.local/share/applications/figaro-settings.desktop"
    chmod 644 "$HOME/.local/share/applications/figaro-settings.desktop"
    echo "   desktop entry installed"

    # The brand icon is the assistant's speaking orb, rendered from the real
    # QML (assets/icons), installed into the hicolor theme the desktop reads.
    for size in 512 256 128 64 48 32; do
      install -Dm644 "$repo/assets/icons/figaro-$size.png" \
        "$HOME/.local/share/icons/hicolor/${size}x${size}/apps/figaro.png"
    done
    # The settings window draws its own macOS-style title bar, so the KWin
    # decoration has to be turned off or the same three buttons appear twice.
    if command -v node >/dev/null 2>&1; then
      node "$repo/scripts/install-kwin-rule.mjs" || echo "   (kwin rule not installed; the window will have a system title bar)"
      qdbus6 org.kde.KWin /KWin org.kde.KWin.reconfigure >/dev/null 2>&1 || true
    fi
    gtk-update-icon-cache -f -t "$HOME/.local/share/icons/hicolor" >/dev/null 2>&1 || true
    update-desktop-database "$HOME/.local/share/applications" >/dev/null 2>&1 || true
    echo "   icon installed (speaking orb, figaro.png)"
  fi
fi


echo "== figaro CLI"
local_bin="${HOME}/.local/bin"
mkdir -p "$local_bin"
cat > "$local_bin/figaro" <<WRAP
#!/bin/sh
# Figaro CLI launcher (generated by install.sh; re-run install.sh after moving the checkout)
if [ -z "\${XDG_RUNTIME_DIR:-}" ]; then
  XDG_RUNTIME_DIR="/run/user/\$(id -u)"
  export XDG_RUNTIME_DIR
fi
exec "$node" "$repo/bin/figaro" "\$@"
WRAP
chmod +x "$local_bin/figaro"
echo "   figaro 命令 -> $local_bin/figaro"
case ":${PATH}:" in
  *":${local_bin}:"*) ;;
  *)
    rc="${HOME}/.bashrc"
    if ! grep -q 'figaro CLI: ~/.local/bin' "$rc" 2>/dev/null; then
      {
        printf '\n# figaro CLI: ~/.local/bin on PATH\n'
        printf 'case ":$PATH:" in *":%s:"*) ;; *) export PATH="%s:$PATH" ;; esac\n' "$local_bin" "$local_bin"
      } >> "$rc"
      echo "   已将 ~/.local/bin 写入 ~/.bashrc（新开终端或 source ~/.bashrc 后生效）"
    fi
    ;;
esac

echo "== systemd units"
mkdir -p "$unit_dir"
render "$repo/systemd/figaro.service.in" "$unit_dir/figaro.service"
render "$repo/systemd/figaro-ui.service.in" "$unit_dir/figaro-ui.service"
systemctl --user daemon-reload
systemctl --user enable --now figaro.service
systemctl --user enable --now figaro-ui.service

echo "== RAG (LightRAG long-term memory)"
rag_home="${FIGARO_LIGHTRAG_HOME:-$HOME/.local/share/figaro/lightrag}"
if [[ -x "$rag_home/venv/bin/lightrag-server" && -f "$rag_home/.env" && -f "$repo/scripts/rag/minimax-embed-proxy.mjs" ]]; then
  render "$repo/systemd/figaro-rag-embed.service.in" "$unit_dir/figaro-rag-embed.service"
  render "$repo/systemd/figaro-rag.service.in" "$unit_dir/figaro-rag.service"
  sed -i "s|@LIGHTRAG_HOME@|$rag_home|g" "$unit_dir/figaro-rag-embed.service" "$unit_dir/figaro-rag.service"
  systemctl --user daemon-reload
  systemctl --user enable --now figaro-rag-embed.service
  systemctl --user enable --now figaro-rag.service
  echo "   RAG 服务已启用（$rag_home，127.0.0.1:9621/9622；配置见 docs/rag.md）"
else
  echo "   跳过：未检测到 $rag_home/venv/bin/lightrag-server（按 docs/rag.md 安装后重跑）"
fi

echo "== status"
systemctl --user --no-pager --lines=0 status figaro.service figaro-ui.service || true
echo
echo "ask:   $node $repo/bin/figaro ask \"现在几点？用 bash 看一下\""
echo "watch: journalctl --user -u figaro -f"
